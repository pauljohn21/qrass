            // `cargo run -q -p sasspile --example calibrate_space -- a98_rgb xyz 2.19921875`，候选值与残差读在
            // `tasks.md` 9.17 —— 那条曲线此前在 `super::matrix` 里站在这一对的另一侧，而那才是这里错得更狠的那一半。
            //
            // 只有 `[0][0]` 保留了抄本：其余每一项错过拟合都多于它自己两个方向的散布，而 Z 输出行是其中最差的。
