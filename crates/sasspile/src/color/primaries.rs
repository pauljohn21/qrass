            // 变体都是 `regress=0`，拟合的第 2 行赢下更多行；见 `tasks.md` 9.20。`[2][0]` 是这一行唯一留下的项：
            // 拟合为它印 `-0.0`，与抄的 `0.0` 之差是 `0`，而一个带符号的零不是归档会有异议的一个数字。
            //
            // 第 1 行正是那条无曲线的白点不变量最先指认的：抄的第 1 行和是 `0.9999999304`，而
